/** Hand-written entries win over bulk-generated ones. */
const DICTIONARY: Record<string, [string, string]> = { ...GENERATED, ...TRANSLATIONS };

function normalize(text: string): string {
  return text.replace(/\s+/g, ' ').trim().toLocaleLowerCase('fr');
}

const NORMALIZED: Record<string, [string, string]> = {};
for (const [key, value] of Object.entries(DICTIONARY)) NORMALIZED[normalize(key)] = value;

export function translate(text: string, lang: Lang): string {
  if (lang === 'fr') return text;
  const entry = DICTIONARY[text] ?? NORMALIZED[normalize(text)];
  return entry?.[lang === 'en' ? 0 : 1] ?? text;
}

